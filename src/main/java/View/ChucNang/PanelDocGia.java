        private void searchDG() {
        try {
            String searchText = txtTimKiem.getText().trim();
            String searchCriteria = (String) cbTimKiem.getSelectedItem();

            List<DocGia> dgList = docgiaDAO.getAllDocGia();
            DefaultTableModel model = (DefaultTableModel) tableDG.getModel();
            model.setRowCount(0);

            for (DocGia dg : dgList) {
                boolean match = false;

                // Kiểm tra tiêu chí tìm kiếm
                if (searchCriteria.equals("Mã độc giả") && !searchText.isEmpty()) {
                    match = String.valueOf(dg.getMadocgia()).contains(searchText);
                } else if (searchCriteria.equals("Tên độc giả") && !searchText.isEmpty()) {
                    match = dg.getTendocgia().toLowerCase().contains(searchText.toLowerCase());
                } else if (searchText.isEmpty()) {
                    match = true; // Hiển thị tất cả nếu không có từ khóa
                }

                if (match) {
                    model.addRow(new Object[]{
                        dg.getMadocgia(),
                        dg.getTendocgia(),
                        dg.getSdt(),
                        dg.getEmail(),
                        dg.getDiachi()
                    });
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi tìm kiếm độc giả: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }
