    private void btnNhapDuLieuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNhapDuLieuActionPerformed
    JFileChooser fileChooser = new JFileChooser();
    fileChooser.setDialogTitle("Chọn file Excel để nhập dữ liệu độc giả");
    fileChooser.setFileFilter(new javax.swing.filechooser.FileFilter() {
        @Override
        public boolean accept(File f) {
            return f.isDirectory() || f.getName().toLowerCase().endsWith(".xlsx");
        }

        @Override
        public String getDescription() {
            return "Excel Files (*.xlsx)";
        }
    });

    int result = fileChooser.showOpenDialog(this);
    if (result == JFileChooser.APPROVE_OPTION) {
        File selectedFile = fileChooser.getSelectedFile();
        try (FileInputStream fis = new FileInputStream(selectedFile); Workbook workbook = new XSSFWorkbook(fis)) {
            Sheet sheet = workbook.getSheetAt(0);
            int successCount = 0;
            for (int i = 1; i <= sheet.getLastRowNum(); i++) {
                Row row = sheet.getRow(i);
                if (row == null) {
                    continue;
                }

                try {
                    // Kiểm tra dữ liệu từ Excel
                    String tendocgia = row.getCell(1) != null ? row.getCell(1).getStringCellValue() : "";
                    String sdt = row.getCell(2) != null ? row.getCell(2).getStringCellValue() : "";
                    String email = row.getCell(3) != null ? row.getCell(3).getStringCellValue() : "";
                    String diachi = row.getCell(4) != null ? row.getCell(4).getStringCellValue() : "";

                    if (!isValidName(tendocgia)) {
                        JOptionPane.showMessageDialog(this, "Tên độc giả ở dòng " + (i + 1) + " không hợp lệ!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
                        continue;
                    }
                    if (!isValidPhoneNumber(sdt)) {
                        JOptionPane.showMessageDialog(this, "Số điện thoại ở dòng " + (i + 1) + " không hợp lệ!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
                        continue;
                    }
                    if (!isValidEmail(email)) {
                        JOptionPane.showMessageDialog(this, "Email ở dòng " + (i + 1) + " không hợp lệ!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
                        continue;
                    }
                    if (!isValidAddress(diachi)) {
                        JOptionPane.showMessageDialog(this, "Địa chỉ ở dòng " + (i + 1) + " không hợp lệ!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
                        continue;
                    }

                    DocGia dg = new DocGia();
                    dg.setMadocgia((int) row.getCell(0).getNumericCellValue());
                    dg.setTendocgia(tendocgia);
                    dg.setSdt(sdt);
                    dg.setEmail(email);
                    dg.setDiachi(diachi);

                    if (docgiaDAO.addDG(dg)) {
                        successCount++;
                    } else {
                        JOptionPane.showMessageDialog(this, "Không thể thêm độc giả ở dòng " + (i + 1), "Cảnh báo", JOptionPane.WARNING_MESSAGE);
                    }
                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(this, "Lỗi khi đọc dòng " + (i + 1) + ": " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
                }
            }

            loadTableData();
            JOptionPane.showMessageDialog(this, "Đã nhập thành công " + successCount + " độc giả!", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi đọc file Excel: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnNhapDuLieuActionPerformed

