            private void addDG() {
    try {
        String tendocgia = txtTenDG.getText().trim();
        String sdt = txtSdt.getText().trim();
        String email = txtEmail.getText().trim();
        String diachi = txtDiaChi.getText().trim();

        // Kiểm tra tên độc giả
        if (!isValidName(tendocgia)) {
            JOptionPane.showMessageDialog(this, "Tên độc giả không hợp lệ!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Kiểm tra số điện thoại
        if (!isValidPhoneNumber(sdt)) {
            JOptionPane.showMessageDialog(this, "Số điện thoại không hợp lệ! Phải bắt đầu bằng 0 và có đúng 10 chữ số.", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Kiểm tra email
        if (!isValidEmail(email)) {
            JOptionPane.showMessageDialog(this, "Email không hợp lệ! Vui lòng nhập đúng định dạng (ví dụ: ten@domain.com).", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Kiểm tra địa chỉ
        if (!isValidAddress(diachi)) {
            JOptionPane.showMessageDialog(this, "Địa chỉ không hợp lệ!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (docgiaDAO.isDuplicatePhoneOrEmail(sdt, email, 0)) {
            JOptionPane.showMessageDialog(this, "Số điện thoại hoặc email đã tồn tại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        DocGia dg = new DocGia();
        dg.setTendocgia(tendocgia);
        dg.setSdt(sdt);
        dg.setEmail(email);
        dg.setDiachi(diachi);

        if (docgiaDAO.addDG(dg)) {
            JOptionPane.showMessageDialog(this, "Thêm độc giả thành công!");
            loadTableData();
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm độc giả thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Lỗi khi thêm độc giả: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
    }
}
    
