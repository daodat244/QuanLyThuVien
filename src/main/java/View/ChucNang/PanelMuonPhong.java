    private void tableMuonPhongMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMuonPhongMouseClicked
        // TODO add your handling code here:
        int row = tableMuonPhong.getSelectedRow();
                if (row >= 0) {
                    int maphong = Integer.parseInt(tableMuonPhong.getValueAt(row, 1).toString());
                    lblTenDocGia.setText(tableMuonPhong.getValueAt(row, 2).toString());
                    txaGhiChu.setText(tableMuonPhong.getValueAt(row, 5).toString());
                    
                    for (int i = 0; i < cbPhong.getItemCount(); i++) {
                    if (cbPhong.getItemAt(i).getMaphong() == maphong) {
                        cbPhong.setSelectedIndex(i);
                        break;
                    }
                }
                }
    }//GEN-LAST:event_tableMuonPhongMouseClicked

