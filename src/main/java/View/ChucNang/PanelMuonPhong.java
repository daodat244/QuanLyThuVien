    private void addMuonPhong() {
        try {
            // Tạo đối tượng MuonPhong
            MuonPhong muonPhong = new MuonPhong();

            // Lấy phòng học được chọn từ combo box
            PhongHoc selectedPhong = (PhongHoc) cbPhong.getSelectedItem();
            if (selectedPhong == null) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn phòng học!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }
            muonPhong.setMaphong(selectedPhong.getMaphong());

            // Lấy mã độc giả từ lblTenDocGia (phải kiểm tra mã đã được nhập trước đó)
            String inputMaDocGia = txtMaDocGia.getText().trim();
            if (inputMaDocGia.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập mã độc giả trước khi thêm phiếu mượn!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }
            int madocgia = Integer.parseInt(inputMaDocGia);
            muonPhong.setMadocgia(madocgia);

            // Lấy thời gian mượn và trả từ DateTimePicker
            LocalDateTime tgMuon = dtpTGmuon.getDateTimeStrict();
            LocalDateTime tgTra = dtpTGtra.getDateTimeStrict();
            if (tgMuon == null || tgTra == null) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn đầy đủ thời gian mượn và trả!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }
            //tgian muon ko được lớn hơn tgian trả
            if (tgMuon.isAfter(tgTra)) {
            JOptionPane.showMessageDialog(this, "Thời gian mượn phải nhỏ hơn thời gian trả!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
            }
            muonPhong.setTgianmuon(tgMuon);
            muonPhong.setTgiantra(tgTra);

            // Lấy ghi chú từ TextArea
            String ghichu = txaGhiChu.getText().trim();
            muonPhong.setGhichu(ghichu);

            // Thêm phiếu mượn vào CSDL
            if (muonPhongDAO.addMuonPhong(muonPhong)) {
                JOptionPane.showMessageDialog(this, "Thêm phiếu mượn phòng thành công!");
                loadTableData();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Thêm phiếu mượn phòng thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Mã độc giả không hợp lệ!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi thêm phiếu mượn phòng: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }

    
    private void updateMuonPhong() {
        int row = tableMuonPhong.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một phiếu mượn phòng để sửa!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // Tạo đối tượng MuonPhong
            MuonPhong muonPhong = new MuonPhong();
            muonPhong.setMaphieump(Integer.parseInt(tableMuonPhong.getValueAt(row, 0).toString()));
            muonPhong.setGhichu(txaGhiChu.getText().trim());

            // Lấy ngày và giờ từ DatePicker và TimePicker
            LocalDateTime tgMuon = dtpTGmuon.getDateTimeStrict();
            LocalDateTime tgTra = dtpTGtra.getDateTimeStrict();

            // Kiểm tra dữ liệu đầu vào
            if (tgMuon == null || tgTra == null) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn đầy đủ thời gian mượn và trả!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }
            //tgian muon ko được lớn hơn tgian trả
            if (tgMuon.isAfter(tgTra)) {
            JOptionPane.showMessageDialog(this, "Thời gian mượn phải nhỏ hơn thời gian trả!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
            }
            
            muonPhong.setTgianmuon(tgMuon);
            muonPhong.setTgiantra(tgTra);
            
            // Lấy mã độc giả từ txtMaDocGia
            String inputMaDocGia = txtMaDocGia.getText().trim();
            if (inputMaDocGia.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập mã độc giả!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }
            int madocgia = Integer.parseInt(inputMaDocGia);
            muonPhong.setMadocgia(madocgia);
            

            // Kiểm tra Phòng Học được chọn
            PhongHoc selectedPhongHoc = (PhongHoc) cbPhong.getSelectedItem();
            if (selectedPhongHoc == null) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn một Phòng học!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Gán maphieump từ nhà xuất bản được chọn
            muonPhong.setMaphong(selectedPhongHoc.getMaphong());

            if (muonPhongDAO.updateMuonPhong(muonPhong)) {
                JOptionPane.showMessageDialog(this, "Sửa Phiếu mượn phòng thành công!");
                loadTableData();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Sửa Phiếu mượn phòng thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập số hợp lệ", "Lỗi", JOptionPane.ERROR_MESSAGE);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi sửa phiếu mượn phòng: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    
    
    private void deleteMuonPhong() {
        int row = tableMuonPhong.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một phiếu mượn phòng để xóa!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa phiếu mượn phòng này?", "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                int maphieump = Integer.parseInt(tableMuonPhong.getValueAt(row, 0).toString());
                if (muonPhongDAO.deleteMuonPhong(maphieump)) {
                    JOptionPane.showMessageDialog(this, "Xóa phiếu mượn phòng thành công!");
                    loadTableData();
                    clearFields();
                } else {
                    JOptionPane.showMessageDialog(this, "Xóa phiếu mượn phòng thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                }
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Lỗi khi xóa phiếu mượn phòng: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        }
    }
    
