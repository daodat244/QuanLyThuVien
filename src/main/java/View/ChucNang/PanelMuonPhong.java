    private void btnKiemTraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKiemTraActionPerformed
        // TODO add your handling code here:
            try {
                String input = txtMaDocGia.getText().trim();
                if (input.isEmpty()) {
                    lblTenDocGia.setText("Vui lòng nhập mã độc giả.");
                    return;
                }

                int madocgia = Integer.parseInt(input);

                DocGiaDAO docGiaDAO = new DocGiaDAO();
                DocGia docGia = docGiaDAO.getDocGiaById(madocgia);

                if (docGia != null) {
                    lblTenDocGia.setText(docGia.getTendocgia());
                } else {
                    lblTenDocGia.setText("Không tìm thấy độc giả.");
                }

            } catch (NumberFormatException ex) {
                lblTenDocGia.setText("Mã độc giả không hợp lệ.");
            }catch (SQLException ex) {
                lblTenDocGia.setText("Lỗi kết nối CSDL: " + ex.getMessage());
            }
    }//GEN-LAST:event_btnKiemTraActionPerformed

