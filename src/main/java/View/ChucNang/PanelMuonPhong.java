    private void searchTheoTenDocGia() {
    String keyword = txtTimKiem.getText().trim().toLowerCase();
        if (keyword.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập tên độc giả cần tìm!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            List<Object[]> mpList = muonPhongDAO.getAllMuonPhongWithDetails();
            DefaultTableModel model = (DefaultTableModel) tableMuonPhong.getModel();
            model.setRowCount(0);

            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm");

            for (Object[] row : mpList) {
                int maphieu = (int) row[0];
                String tenPhong = (String) row[1];
                String tenDocGia = (String) row[2];
                LocalDateTime tgMuon = (LocalDateTime) row[3];
                LocalDateTime tgTra = (LocalDateTime) row[4];
                String ghiChu = (String) row[5];

                if (!tenDocGia.toLowerCase().contains(keyword)) continue;

                model.addRow(new Object[]{
                    maphieu,
                    tenPhong,
                    tenDocGia,
                    tgMuon != null ? tgMuon.format(formatter) : "",
                    tgTra != null ? tgTra.format(formatter) : "",
                    ghiChu
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi tìm kiếm: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }


    
