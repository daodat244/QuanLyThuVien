    private void loadTableData() {
        try {
            List<PhieuTra> phieuTraList = phieuTraDAO.getAllPhieuTra();
            DefaultTableModel model = (DefaultTableModel) tablePhieuTra.getModel();
            model.setRowCount(0);
            for (PhieuTra pt : phieuTraList) {
                String tendocgia = getTenDocGia(pt.getMadocgia());
                String tennv = getTenNhanVien(pt.getManv());
                String tensach = getTenSach(pt.getMasach());
                model.addRow(new Object[]{
                    pt.getMaphieutra(),
                    pt.getMaphieu(),
                    tendocgia != null ? tendocgia : "Không xác định",
                    tennv != null ? tennv : "Không xác định",
                    tensach != null ? tensach : "Không xác định",
                    pt.getNgaymuon(),
                    pt.getNgaytradukien(),
                    pt.getNgaytrathucte(),
                    pt.getPhiphat(),
                    pt.getGhichu()
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi tải dữ liệu phiếu trả: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }
    private void clearFields() {
        txtMaphieu.setText("");
        tblMaphieu2.setText("");
        date.clear();
        tblghichu.setText("");
        selectedPhieuMuon = null;
    }

    private String getTenDocGia(int madocgia) throws SQLException {
        DocGia docGia = docGiaDAO.getDocGiaById(madocgia);
        return docGia != null ? docGia.getTendocgia() : null;
    }

    private String getTenNhanVien(int manv) throws SQLException {
        NhanVien nv = nhanVienDAO.getNhanVienById(manv);
        return nv != null ? nv.getTennv() : null;
    }

    private String getTenSach(int masach) throws SQLException {
        Sach sach = sachDAO.getSachById(masach);
        return sach != null ? sach.getTensach() : null;
    }
