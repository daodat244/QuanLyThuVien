    private void btnKiemtraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKiemtraActionPerformed
        try {
            int maphieu = Integer.parseInt(txtMaphieu.getText().trim());
            PhieuMuon pm = phieuTraDAO.getPhieuMuonById(maphieu);
            if (pm != null) {
                if ("Đã trả".equals(pm.getTrangthai())) {
                    JOptionPane.showMessageDialog(this, "Phiếu mượn này đã được trả!", "Thông báo", JOptionPane.WARNING_MESSAGE);
                    selectedPhieuMuon = null;
                    tblMaphieu2.setText("Đã trả");
                } else {
                    selectedPhieuMuon = pm;
                    tblMaphieu2.setText("Đang mượn");
                }
            } else {
                selectedPhieuMuon = null;
                tblMaphieu2.setText("Không tồn tại");
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Mã phiếu phải là số!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            tblMaphieu2.setText("");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi kiểm tra: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
            tblMaphieu2.setText("");
        }
    }//GEN-LAST:event_btnKiemtraActionPerformed

    private void btntrasachActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btntrasachActionPerformed
if (selectedPhieuMuon == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng kiểm tra mã phiếu mượn trước!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        LocalDateTime ngaytrathucte = date.getDateTimePermissive();
        if (ngaytrathucte == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn ngày trả!", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn trả sách này?", "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            Connection conn = null;
            try {
                conn = ConnectToSQLServer.getConnection();
                conn.setAutoCommit(false); // Bắt đầu giao dịch

                // Tính phí phạt: 5000 VNĐ/ngày trễ
                long daysLate = ChronoUnit.DAYS.between(selectedPhieuMuon.getNgayTraDuKien().toLocalDate(), ngaytrathucte.toLocalDate());
                double phiphat = daysLate > 0 ? daysLate * 5000 : 0;

                // Bước 1: Cập nhật trạng thái trong phieumuon thành "Đã trả"
                if (!phieuMuonDAO.updateTrangThai(selectedPhieuMuon.getMaphieu(), "Đã trả", conn)) {
                    throw new SQLException("Không thể cập nhật trạng thái phiếu mượn.");
                }

                // Bước 2: Thêm bản ghi vào phieutra
                PhieuTra pt = new PhieuTra(
                    0, // maphieutra sẽ tự tăng
                    selectedPhieuMuon.getMaphieu(),
                    selectedPhieuMuon.getMadocgia(),
                    selectedPhieuMuon.getManv(),
                    selectedPhieuMuon.getMasach(),
                    selectedPhieuMuon.getNgaymuon(),
                    selectedPhieuMuon.getNgayTraDuKien(),
                    ngaytrathucte,
                    phiphat,
                    tblghichu.getText().trim()
                );

                if (phieuTraDAO.addPhieuTra(pt, conn)) {
                    conn.commit(); // Xác nhận giao dịch
                    JOptionPane.showMessageDialog(this, "Trả sách thành công! Phí phạt: " + phiphat + " VNĐ");
                    loadTableData(); // Làm mới bảng trong PanelPhieuTra
                    clearFields();

                    // Làm mới bảng trong PanelPhieuMuon
                    Menu menu = (Menu) SwingUtilities.getWindowAncestor(this);
                    if (menu != null) {
                        PanelPhieuMuon panelPhieuMuon = menu.getPanelPhieuMuon();
                        if (panelPhieuMuon != null) {
                            panelPhieuMuon.refreshTableData();
                        }
                    }
                } else {
                    conn.rollback(); // Hoàn tác nếu thất bại
                    JOptionPane.showMessageDialog(this, "Trả sách thất bại khi thêm vào phieutra!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                }
            } catch (SQLException ex) {
                try {
                    if (conn != null) conn.rollback(); // Hoàn tác nếu có lỗi
                } catch (SQLException e) {
                    e.printStackTrace();
                }
                JOptionPane.showMessageDialog(this, "Lỗi khi trả sách: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
            } finally {
                try {
                    if (conn != null) {
                        conn.setAutoCommit(true); // Khôi phục chế độ auto-commit
                        conn.close();
                    }
                } catch (SQLException e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_btntrasachActionPerformed

